"""Pieces of other Ion tools (ion-repo#T-418): laid, handed over, updated, or left with a note."""

import subprocess
from pathlib import Path

import pytest
import yaml

from ion_repo import pieces

HEAL = "config/vps/heal.sh"


def _git(cwd: Path, *args: str) -> None:
    subprocess.run(["git", *args], cwd=cwd, check=True, capture_output=True)


def _commit(cwd: Path, message: str) -> None:
    _git(cwd, "add", "-A")
    _git(cwd, "commit", "-q", "-m", message)


def _tool(tmp_path: Path) -> Path:
    """ion-host's repo as T-394 decided it: `copier.yml` at its root, the files in `piece/`."""
    tool = tmp_path / "ion-host"
    (tool / "piece/config/vps").mkdir(parents=True)
    (tool / "copier.yml").write_text(
        "_subdirectory: piece\n_templates_suffix: .jinja\n"
        "_answers_file: .copier-answers.ion-host.yml\n"
    )
    (tool / "piece/{{_copier_conf.answers_file}}.jinja").write_text(
        "{{ _copier_answers|to_nice_yaml }}"
    )
    (tool / f"piece/{HEAL}.jinja").write_text("# {{ title }}\nNAME={{ name }}\nstep one\n")
    # ion-repo's answers read, never declared: a `when: false` question is hidden, and Copier's
    # update renders the new revision without it (`-heal.timer`, `demo-heal.timer` deleted).
    (tool / "piece/config/vps/{{ name }}-heal.timer.jinja").write_text("[Timer]\n")
    _git(tool, "init", "-q", "-b", "main")
    _commit(tool, "piece")
    _git(tool, "tag", "v0.1.0")
    return tool


def _template(tmp_path: Path, tool: Path | str) -> Path:
    """ion-repo's template, reduced to its table of pieces."""
    template = tmp_path / "ion-repo"
    template.mkdir()
    row = {
        "tool": "ion-host",
        "repo": "antoine-tena/ion-host",
        "plugin": "host",
        "when": {"deploy": "vps"},
        "template": str(tool),
    }
    (template / "copier.yml").write_text(
        yaml.safe_dump({"pieces": {"type": "yaml", "when": False, "default": [row]}})
    )
    return template


def _project(tmp_path: Path, **answers: object) -> Path:
    project = tmp_path / "demo"
    project.mkdir()
    (project / ".copier-answers.yml").write_text(
        yaml.safe_dump({"_commit": "v9", "name": "demo", "title": "Demo", **answers})
    )
    _git(project, "init", "-q", "-b", "develop")
    _commit(project, "init")
    return project


def test_a_new_piece_reads_every_answer_and_records_none(tmp_path: Path) -> None:
    project = _project(tmp_path, deploy="vps")
    pieces.apply_pieces(project, str(_template(tmp_path, _tool(tmp_path))), [])
    assert (project / HEAL).read_text() == "# Demo\nNAME=demo\nstep one\n"
    recorded = yaml.safe_load((project / ".copier-answers.ion-host.yml").read_text())
    assert set(recorded) == {"_commit", "_src_path"}


def test_handed_over_then_merged_with_the_tools_next_release(tmp_path: Path) -> None:
    """The sandbox's scenario (T-394): generated by ion-repo, changed by hand, handed over to the
    tool, then the tool's next release merged with the change."""
    tool = _tool(tmp_path)
    project = _project(tmp_path, deploy="vps")
    (project / HEAL).parent.mkdir(parents=True)
    (project / HEAL).write_text("# Demo\nNAME=demo\nstep one\n# changed by hand\n")
    (project / HEAL).chmod(0o755)
    _commit(project, "heal.sh, by ion-repo then by hand")
    # The release of ion-repo that drops the file: Copier deletes it, even changed.
    (project / HEAL).unlink()
    template = str(_template(tmp_path, tool))
    pieces.apply_pieces(project, template, [])
    assert (project / HEAL).read_text().endswith("# changed by hand\n")
    assert (project / ".copier-answers.ion-host.yml").is_file()
    assert (project / HEAL).stat().st_mode & 0o111
    _commit(project, "handover")
    (tool / f"piece/{HEAL}.jinja").write_text("# {{ title }}, healed\nNAME={{ name }}\nstep one\n")
    _commit(tool, "next release")
    _git(tool, "tag", "v0.1.1")
    pieces.apply_pieces(project, template, [])
    assert sorted(p.name for p in (project / "config/vps").iterdir()) == [
        "demo-heal.timer",
        "heal.sh",
    ]
    merged = (project / HEAL).read_text()
    assert merged == "# Demo, healed\nNAME=demo\nstep one\n# changed by hand\n"
    recorded = yaml.safe_load((project / ".copier-answers.ion-host.yml").read_text())
    assert set(recorded) == {"_commit", "_src_path"}


def test_an_unreachable_piece_gets_a_note_and_nothing_else(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    project = _project(tmp_path, deploy="vps")
    missing = tmp_path / "no-access" / "ion-host.git"
    pieces.apply_pieces(project, str(_template(tmp_path, missing)), [])
    assert "cannot be reached" in capsys.readouterr().out + capsys.readouterr().err
    assert not (project / HEAL).exists()
    assert not (project / ".copier-answers.ion-host.yml").exists()


def test_frozen_files_are_spared(tmp_path: Path) -> None:
    project = _project(tmp_path, deploy="vps")
    pieces.apply_pieces(project, str(_template(tmp_path, _tool(tmp_path))), [HEAL])
    assert not (project / HEAL).exists()


@pytest.mark.parametrize(
    ("answers", "expected"),
    [
        ({"name": "demo", "deploy": "vps"}, True),
        ({"name": "demo", "deploy": "none"}, False),
        ({"name": "ion-host", "deploy": "vps"}, False),
    ],
)
def test_the_answers_bring_a_piece(answers: dict[str, object], expected: bool) -> None:
    host = pieces.Piece("ion-host", "antoine-tena/ion-host", "host", {"deploy": "vps"}, "")
    assert pieces.brought(host, answers) is expected


def test_ion_host_ships_its_skills_only_while_its_repo_is_private() -> None:
    """No file leaves ion-repo's template before its tool's repo is public (T-394)."""
    (host,) = [piece for piece in pieces.table("") if piece.tool == "ion-host"]
    assert (host.repo, host.plugin, host.when, host.template) == (
        "antoine-tena/ion-host",
        "host",
        {"deploy": "vps"},
        "",
    )
