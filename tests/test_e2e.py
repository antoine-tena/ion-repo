"""End to end: what kiln promises, checked for real.

- every framework is generated by `kiln new`, installed, and passes its own `kiln check`;
- a project made by an earlier release moves to this one with `kiln update`, without conflicts,
  and still passes its checks;
- every release since v0.3.0 moves to this one the way users do it: through an installed tool
  and the template on GitHub, no `KILN_TEMPLATE` shortcut (the shortcut hid the bug of T-147).

Slow and networked (PyPI, npm, Maven Central): left out of the default run, played by
`uv run pytest -m e2e` and by kiln's CI on release branches and every night. The generated
projects take a few gigabytes: where `/tmp` is a RAM disk (WSL), add
`--basetemp ~/.cache/kiln-e2e`.
"""

import os
import shutil
import subprocess
from pathlib import Path

import copier
import pytest

from kiln import renames
from kiln.versions import release_version

REPO = Path(__file__).resolve().parent.parent
TIMEOUT = 1800
pytestmark = pytest.mark.e2e

# Each framework at least once, in the pairs a project is likely to use.
STACKS = [
    ("django", "nuxt"),
    ("fastapi", "next"),
    ("fastapi", "dash"),
    ("data", "streamlit"),
    ("cli", "none"),
    ("java", "none"),
    ("none", "astro"),
]
UPGRADED_STACKS = [
    ("django", "nuxt"),
    ("fastapi", "none"),
    ("data", "streamlit"),
    ("java", "none"),
]
# The oldest release a project may still follow, and the stack every release is tried with.
OLDEST_UPDATED = "v0.3.0"
LIGHT_STACK = ("cli", "none")
GITHUB_TEMPLATE = "https://github.com/antoine-tena/kiln"
# A release no one has: the tag the checkout under test is given, newer than any real one.
RELEASE_UNDER_TEST = "v99.0.0-rc.1"
PNPM_FRONTENDS = {"nuxt", "next", "astro"}


@pytest.fixture
def kiln_env(tmp_path: Path) -> dict[str, str]:
    """kiln as a newcomer runs it, with this checkout as its template; a machine config of its
    own, so that nothing is asked and the user's Claude Code status line is left alone."""
    config_dir = tmp_path / "config" / "kiln"
    config_dir.mkdir(parents=True)
    (config_dir / "config.toml").write_text('system = "linux"\nstatusline = "custom"\n')
    return {
        **os.environ,
        "XDG_CONFIG_HOME": str(config_dir.parent),
        "KILN_TEMPLATE": str(REPO),
        "NO_COLOR": "1",
    }


def run_kiln(*args: str, cwd: Path, env: dict[str, str]) -> subprocess.CompletedProcess[str]:
    kiln = shutil.which("kiln")
    assert kiln is not None, "kiln is not installed in this environment (uv sync)"
    return subprocess.run(
        [kiln, *args],
        cwd=cwd,
        env=env,
        stdin=subprocess.DEVNULL,
        capture_output=True,
        text=True,
        timeout=TIMEOUT,
        check=False,
    )


def require_tools(backend: str, frontend: str) -> None:
    needed = ["pnpm"] if frontend in PNPM_FRONTENDS else []
    needed += ["java"] if backend == "java" else []
    missing = [tool for tool in needed if shutil.which(tool) is None]
    if missing:
        pytest.skip(f"missing on this machine: {', '.join(missing)}")


def assert_succeeded(completed: subprocess.CompletedProcess[str]) -> None:
    assert completed.returncode == 0, completed.stdout[-6000:] + completed.stderr[-3000:]


# A French project too: its user-facing texts change, its checks must not.
LANGUAGES = {("fastapi", "dash"): "fr", ("cli", "none"): "fr"}


@pytest.mark.parametrize(("backend", "frontend"), STACKS)
def test_a_new_project_passes_its_own_checks(
    tmp_path: Path, kiln_env: dict[str, str], backend: str, frontend: str
) -> None:
    require_tools(backend, frontend)
    language = LANGUAGES.get((backend, frontend), "en")

    created = run_kiln(
        "new", "demo", "--no-github", "--backend", backend, "--frontend", frontend,
        "--language", language, cwd=tmp_path, env=kiln_env,
    )  # fmt: skip
    assert_succeeded(created)
    assert_succeeded(run_kiln("check", cwd=tmp_path / "demo", env=kiln_env))


def git_tags(*options: str) -> list[str]:
    return subprocess.run(
        ["git", "tag", "-l", "v*", "--sort=-v:refname", *options],
        cwd=REPO,
        capture_output=True,
        text=True,
        check=True,
    ).stdout.split()


def previous_releases() -> list[str]:
    """The last promoted release and the last candidate, those that projects follow today."""
    tags = git_tags("--merged", "HEAD")
    promoted = next((tag for tag in tags if "-rc." not in tag), None)
    candidate = next((tag for tag in tags if "-rc." in tag), None)
    return [tag for tag in dict.fromkeys((promoted, candidate)) if tag is not None]


def every_release() -> list[str]:
    """Every release since the oldest still followed, one tag per commit (a promoted release
    sits on its last candidate's commit), merged or not: a repo may follow a candidate whose
    release branch is not merged back yet."""
    oldest = release_version(OLDEST_UPDATED)
    by_commit: dict[str, str] = {}
    for tag in git_tags():
        version = release_version(tag)
        if version is None or oldest is None or version < oldest:
            continue
        commit = subprocess.run(
            ["git", "rev-list", "-n", "1", tag], cwd=REPO, capture_output=True, text=True,
            check=True,
        ).stdout.strip()  # fmt: skip
        by_commit.setdefault(commit, tag)
    return list(by_commit.values())


def is_before_english(tag: str) -> bool:
    """A release of kiln 0.3: answers under French names."""
    version = release_version(tag)
    return version is not None and version.release < (0, 4, 0)


def make_old_project(
    destination: Path, tag: str, backend: str, frontend: str, source: str = str(REPO)
) -> None:
    """A project as the release `tag` generated it: rendered, locked, committed, then on a
    work branch, ready for `kiln update`."""
    answers: dict[str, object] = {"name": "demo", "backend": backend, "frontend": frontend}
    copier.run_copy(
        source,
        destination,
        # The answers under the names the template of that release knows.
        data=renames.legacy_answers(answers) if is_before_english(tag) else answers,
        vcs_ref=tag,
        defaults=True,
        quiet=True,
        unsafe=False,
    )
    git = ["git", "-C", str(destination)]
    subprocess.run([*git, "init", "-q", "-b", "main"], check=True)
    for directory in ("backend", "frontend"):
        project = destination / directory
        if (project / "pyproject.toml").exists():
            subprocess.run(["uv", "lock", "-q"], cwd=project, check=True)
        if (project / "package.json").exists():
            subprocess.run(["pnpm", "install", "--lockfile-only"], cwd=project, check=True)
    subprocess.run([*git, "add", "-A"], check=True)
    subprocess.run([*git, "commit", "-q", "-m", f"chore: generated by kiln {tag}"], check=True)
    subprocess.run([*git, "switch", "-q", "-c", "chore/kiln-update"], check=True)


def assert_updated_cleanly(project: Path, tag: str, name: str = "demo") -> None:
    conflicts = subprocess.run(
        ["git", "grep", "-l", "--untracked", "<<<<<<< before updating"],
        cwd=project,
        capture_output=True,
        text=True,
        check=False,
    ).stdout
    assert conflicts == "", f"conflicts left by the update: {conflicts}"
    answers = (project / ".copier-answers.yml").read_text()
    assert f"name: {name}" in answers and "nom:" not in answers
    if is_before_english(tag):
        # A project of kiln 0.3 comes out converted to kiln 0.4's names, its language kept.
        assert "language: fr" in answers
    assert (project / "charter.toml").is_file() and not (project / "charte.toml").exists()
    assert "## Repo map" in (project / "CLAUDE.md").read_text()
    assert not (project / "backend/CLAUDE.md").exists()
    assert (project / ".claude/rules/kiln/charter.md").is_file()


# A published release can no longer be fixed: what its template warns about is tolerated here,
# the current template stays strict (`filterwarnings` of pyproject.toml).
OLD_TEMPLATES = pytest.mark.filterwarnings("default::DeprecationWarning")


@OLD_TEMPLATES
@pytest.mark.parametrize("tag", previous_releases())
@pytest.mark.parametrize(("backend", "frontend"), UPGRADED_STACKS)
def test_a_project_of_an_earlier_release_updates_cleanly(
    tmp_path: Path, kiln_env: dict[str, str], tag: str, backend: str, frontend: str
) -> None:
    require_tools(backend, frontend)
    project = tmp_path / "demo"
    make_old_project(project, tag, backend, frontend)

    updated = run_kiln("update", "--no-deps", cwd=project, env=kiln_env)

    assert_succeeded(updated)
    assert_updated_cleanly(project, tag)


@pytest.fixture(scope="session")
def released_kiln(tmp_path_factory: pytest.TempPathFactory) -> dict[str, str]:
    """This checkout as users get a release: a clone tagged `RELEASE_UNDER_TEST`, installed by
    `uv tool install` in a tool folder of its own, and GitHub's address of kiln sent to the
    clone by git (`url.insteadOf`). Copier keeps a mirror of each remote template, by URL: a
    cache of its own, or the workers would share one "GitHub" (and the machine's would keep the
    fake tag). Only committed changes are under test."""
    root = tmp_path_factory.mktemp("released")
    clone = root / "kiln"
    head = subprocess.run(
        ["git", "-C", str(REPO), "rev-parse", "HEAD"], capture_output=True, text=True, check=True
    ).stdout.strip()
    git = ["git", "-C", str(clone), "-c", "user.name=Test", "-c", "user.email=test@example.com"]
    subprocess.run(["git", "clone", "-q", "--no-local", str(REPO), str(clone)], check=True)
    subprocess.run([*git, "switch", "-q", "--detach", head], check=True)
    # A commit of its own: the tag under test is the only one `git describe` can name.
    subprocess.run([*git, "commit", "-q", "--allow-empty", "-m", "release under test"], check=True)
    subprocess.run([*git, "tag", RELEASE_UNDER_TEST], check=True)
    gitconfig = root / "gitconfig"
    gitconfig.write_text(
        "[user]\n\tname = Test\n\temail = test@example.com\n"
        f'[url "{clone}"]\n\tinsteadOf = {GITHUB_TEMPLATE}.git\n\tinsteadOf = {GITHUB_TEMPLATE}\n'
    )
    config_dir = root / "config" / "kiln"
    config_dir.mkdir(parents=True)
    # The internal channel: the release under test is a candidate.
    (config_dir / "config.toml").write_text(
        'system = "linux"\nstatusline = "custom"\nchannel = "internal"\n'
    )
    env = {
        key: value for key, value in os.environ.items() if key != "KILN_TEMPLATE"
    } | {
        "GIT_CONFIG_GLOBAL": str(gitconfig),
        "GIT_CONFIG_NOSYSTEM": "1",
        "COPIER_CACHE_DIR": str(root / "copier"),
        "XDG_CONFIG_HOME": str(config_dir.parent),
        "UV_TOOL_DIR": str(root / "tools"),
        "UV_TOOL_BIN_DIR": str(root / "bin"),
        "NO_COLOR": "1",
    }  # fmt: skip
    subprocess.run(["uv", "tool", "install", "-q", str(clone)], env=env, check=True)
    env["PATH"] = f"{root / 'bin'}{os.pathsep}{env['PATH']}"
    return env


@OLD_TEMPLATES
@pytest.mark.parametrize("tag", every_release())
def test_every_release_updates_through_the_installed_tool(
    tmp_path: Path, released_kiln: dict[str, str], monkeypatch: pytest.MonkeyPatch, tag: str
) -> None:
    project = tmp_path / "demo"
    # Rendered from GitHub's address, as the project was then: `_src_path` is GitHub.
    for variable in ("GIT_CONFIG_GLOBAL", "COPIER_CACHE_DIR"):
        monkeypatch.setenv(variable, released_kiln[variable])
    make_old_project(project, tag, *LIGHT_STACK, source=f"{GITHUB_TEMPLATE}.git")
    kiln = str(Path(released_kiln["UV_TOOL_BIN_DIR"]) / "kiln")

    version = subprocess.run(
        [kiln, "--version"], env=released_kiln, capture_output=True, text=True, check=True
    )
    updated = subprocess.run(
        [kiln, "update", "--no-deps"],
        cwd=project,
        env=released_kiln,
        stdin=subprocess.DEVNULL,
        capture_output=True,
        text=True,
        timeout=TIMEOUT,
        check=False,
    )

    assert version.stdout.strip() == RELEASE_UNDER_TEST
    assert_succeeded(updated)
    assert f"_commit: {RELEASE_UNDER_TEST}" in (project / ".copier-answers.yml").read_text()
    assert_updated_cleanly(project, tag)


# A repo kept on GitHub for this test only: generated by v0.3.3-rc.2 (Java, like the repo whose
# update to v0.4.0-rc.1 broke), then lived in. Frozen there on purpose, its own CI off.
REHEARSAL_REPO = "https://github.com/antoine-tena/kiln-rehearsal"


def test_the_rehearsal_repo_updates_on_a_clone_and_stays_untouched(
    tmp_path: Path, released_kiln: dict[str, str]
) -> None:
    require_tools("java", "none")
    project = tmp_path / "kiln-rehearsal"
    # Cloned with the test's own git config: kiln's `insteadOf` would catch this address too.
    subprocess.run(["git", "clone", "-q", REHEARSAL_REPO, str(project)], check=True)
    kiln = str(Path(released_kiln["UV_TOOL_BIN_DIR"]) / "kiln")

    rehearsed = subprocess.run(
        [kiln, "update", "--rehearse"],
        cwd=project,
        env=released_kiln,
        stdin=subprocess.DEVNULL,
        capture_output=True,
        text=True,
        timeout=TIMEOUT,
        check=False,
    )

    assert_succeeded(rehearsed)
    assert "rehearsal: updates cleanly" in rehearsed.stdout + rehearsed.stderr
    status = subprocess.run(
        ["git", "status", "--porcelain"], cwd=project, capture_output=True, text=True, check=True
    )
    assert status.stdout == ""
    assert "_commit: v0.3.3-rc.2" in (project / ".copier-answers.yml").read_text()

    # Then for real, in this clone: what the team wrote by hand comes through.
    subprocess.run(["git", "switch", "-q", "-c", "chore/kiln-update"], cwd=project, check=True)
    updated = subprocess.run(
        [kiln, "update", "--no-deps"],
        cwd=project,
        env=released_kiln,
        stdin=subprocess.DEVNULL,
        capture_output=True,
        text=True,
        timeout=TIMEOUT,
        check=False,
    )
    assert_succeeded(updated)
    assert_updated_cleanly(project, "v0.3.3-rc.2", name="kiln-rehearsal")
    assert "## Notes du projet" in (project / "CLAUDE.md").read_text()
    assert "T-02 · Annuler une réservation" in (project / "docs/backlog/backlog.md").read_text()
    assert "Bash(./backend/mvnw -q test)" in (project / ".claude/settings.json").read_text()
    assert (project / "backend/src/main/java/fr/kilnrehearsal/trip/Seats.java").is_file()
