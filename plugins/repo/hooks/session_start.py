#!/usr/bin/env python3
"""SessionStart: offers an up-to-date ion-repo in a repo that ion-repo generated; silent elsewhere.

When a session starts (not on resume nor after /clear), in a repo generated by ion-repo:
1. Tool: if the installed `ion-repo` tool is behind the latest release (tag `vN.M.P` of `main`),
   Claude asks (yes/no) whether to update it, with the plugins of ion-repo's marketplace.
2. Repo: once the tool is up to date, if the repo starts from an older version of the template
   (`_commit` of `.copier-answers.yml`), Claude asks whether to run `ion repo update`.
The question only says from which version to which; above it, at the user's first prompt
(`first_prompt.py`), the logo of ion-repo in color says what the update brings, read from the
`CHANGELOG.md` of the latest release (breaking changes first).

When to ask again after a "no": `reminders.py` (5, 10, 30 then 50 sessions). After 4 "no" to an
update, the question also offers to uninstall ion-repo (tool) or to unlink the repo from ion-repo
(repo). Outside ion-repo repos the hook does nothing: adopting ion-repo is on request only (`ion
repo adopt`, skill `/repo:adopt`). Before kiln 0.4 it also linked the plugin at `.claude/ion-repo`
in every repo: that link is removed.

In a repo ion-repo looks after (ion-repo itself included), Claude is also told when the last CI of
the integration branch is red, to say so before any new work.
Never blocking: three seconds at most per network call, silent without network. A repo opts out
with `git config kiln.update-check false` (`kiln-a-jour.desactive true` before kiln 0.4).
"""

