# Copy of `LOGO` and `LOGO_COLORS` of `src/ion_repo/banner.py` (the hook runs without ion-repo
# importable; `test_session_start.py` checks that they stay the same).
LOGO = (
    "..........dd..",
    "...LLLBBB.bb..",
    "..LWKBBWKBbb..",
    ".LLWKBBWKBBbb.",
    ".LBP.RR..PBbb.",
    ".LBB.RFR..Bbb.",
    ".BBB.FYYF.bbb.",
    "dddddddddddddd",
)
LOGO_COLORS = {
    "L": "185;185;180",
    "B": "140;140;135",
    "b": "95;95;92",
    "d": "180;75;35",
    "W": "255;255;255",
    "K": "25;25;25",
    "P": "230;130;120",
    "R": "205;50;35",
    "F": "247;150;40",
    "Y": "255;225;120",
}
STONE, FIRE, EMBER = LOGO_COLORS["B"], LOGO_COLORS["F"], LOGO_COLORS["R"]
RESET, BOLD = "\033[0m", "\033[1m"
UPPER_HALF, LOWER_HALF, FULL_BLOCK = "▀", "▄", "█"
LOGO_MARGIN, TEXT_GAP = "  ", "   "


def foreground(rgb: str) -> str:
    return f"\033[38;2;{rgb}m"


def render_logo() -> list[str]:
    """The logo in half blocks: one character = two stacked pixels."""

    def cell(top: str, bottom: str) -> str:
        if top == "." and bottom == ".":
            return " "
        if bottom == ".":
            return f"{foreground(LOGO_COLORS[top])}{UPPER_HALF}{RESET}"
        if top == ".":
            return f"{foreground(LOGO_COLORS[bottom])}{LOWER_HALF}{RESET}"
        if top == bottom:
            return f"{foreground(LOGO_COLORS[top])}{FULL_BLOCK}{RESET}"
        colors = foreground(LOGO_COLORS[top]) + f"\033[48;2;{LOGO_COLORS[bottom]}m"
        return f"{colors}{UPPER_HALF}{RESET}"

    return [
        "".join(cell(top, bottom) for top, bottom in zip(top_row, bottom_row, strict=True))
        for top_row, bottom_row in zip(LOGO[0::2], LOGO[1::2], strict=True)
    ]


def notice(tag: str, changes: Changes) -> str:
    """The logo next to what the update brings; a single line with `NO_COLOR`."""
    total = len(changes.breaking) + len(changes.others)
    status = "update available" + (f" · {total} changes" if total > HEADLINES else "")
    shown = headlines(changes)
    if "NO_COLOR" in os.environ:
        return " · ".join([f"ion-repo {tag}", status, *(text for _, text in shown)])
    text_lines = [
        f"{BOLD}ion-repo {tag}{RESET}  {foreground(STONE)}{status}{RESET}",
        *(
            f"{foreground(EMBER)}breaking{RESET} {text}"
            if breaking
            else f"{foreground(FIRE)}+{RESET} {text}"
            for breaking, text in shown
        ),
    ]
    text_lines += [""] * (len(LOGO) // 2 - len(text_lines))
    lines = [
        f"{LOGO_MARGIN}{logo}{TEXT_GAP}{text}".rstrip()
        for logo, text in zip(render_logo(), text_lines, strict=True)
    ]
    # Claude Code prefixes the message with the hook's name: the logo starts on the next line.
    return "\n" + "\n".join(lines)


NOTICES_DIR = reminders.STATE_DIR / "kiln" / "notices"


def save_notice(session_id: str, text: str) -> None:
    """Kept for the first prompt of the session (`first_prompt.py`): shown at startup, the logo
    would come before the user has said anything, far from the question."""
    if not session_id or "/" in session_id:
        return
    NOTICES_DIR.mkdir(parents=True, exist_ok=True)
    (NOTICES_DIR / session_id).write_text(text, encoding="utf-8")


# --- Instructions given to Claude ---


YES, NO = "Update", "Not now"


def answer_command(verdict: str, key: Path | str) -> str:
    return f'`{reminders.SCRIPT} {verdict} "{key}"`'


def tool_question(state: reminders.State, current: str | None, tag: str) -> str:
    choices = f'"{YES}", "{NO}"'
    extra = question_format("ion-repo", current, tag)
    if reminders.is_long_refusal(state, TOOL_KEY):
        choices += ', "Uninstall ion-repo"'
        extra += (
            ' The question text starts with "You have been saying no for a while: do you want '
            'to uninstall ion-repo?". If "Uninstall ion-repo": '
            f"`uv tool uninstall {installed_pypi_name()} && claude plugin uninstall "
            f"repo@ion-repo`, "
            f"then {answer_command('never', TOOL_KEY)}."
        )
    return (
        "The ion-repo tool installed on this machine is behind the latest release. Before anything "
        "else, at the start of your first answer, ask with the AskUserQuestion tool, in the "
        f'user\'s language, whether to update ion-repo ({choices}).{extra} If "{YES}": skill '
        f'`/repo:update` with the argument `tool`. If "{NO}": '
        f"{answer_command('no', TOOL_KEY)}, without updating anything. Then resume their request."
    )


def repo_question(root: Path, commit: str, tag: str, state: reminders.State) -> str:
    choices = f'"{YES}", "{NO}"'
    extra = question_format(root.name, commit, tag)
    if reminders.is_long_refusal(state, str(root)):
        choices += f', "Unlink {root.name} from ion-repo"'
        extra += (
            ' The question text starts with "You have been saying no for a while: do you want '
            f'to unlink {root.name} from ion-repo?". If "Unlink": on a dedicated branch, delete '
            f"`{ANSWERS_FILE}` (ion-repo will no longer update this repo), commit and merge with "
            f"the "
            f"skill `/repo:merge`, then {answer_command('never', root)}."
        )
    return (
        f"ion-repo {tag} is out; {root.name} starts from {commit}. Before anything else, at the "
        "start of your answer, ask with the AskUserQuestion tool, in the user's language, "
        f'whether to update {root.name} ({choices}).{extra} If "{YES}": skill `/repo:update` '
        f'with the argument `repo`. If "{NO}": {answer_command("no", root)}. Then resume their '
        "request."
    )


class Offer(NamedTuple):
    context: str  # for Claude: the question to ask
    notice: str  # for the user: the logo and the update on offer


def offer(
    cwd: str,
    state: reminders.State,
    release: Callable[[], tuple[str, str] | None] = latest_release,
    changelog: Callable[[str], str] | None = None,
) -> Offer | None:
    repo = kiln_repo(cwd)
    if repo is None:
        return None
    root, commit = repo
    reminders.count_session(state, TOOL_KEY)
    reminders.count_session(state, str(root))
    # A "no" to the tool also postpones the repo question: no network until it is due.
    if not reminders.is_due(state, TOOL_KEY):
        return None
    latest = release()
    if latest is None:
        return None
    tag = latest[0]
    repo_due = reminders.is_due(state, str(root)) and is_repo_late(commit, tag)
    install = installed_kiln()
    tool_due = is_beta_tool_outdated(install) if is_beta() else is_tool_outdated(install, *latest)
    if not tool_due and not repo_due:
        return None
    notes = (changelog or fetch_changelog)(tag)
    if not tool_due:
        repo_version = commit if release_key(commit) else None
        return Offer(
            repo_question(root, commit, tag, state),
            notice(tag, changes_between(repo_version, tag, notes)),
        )
    follow_up = ""
    if repo_due:
        follow_up = " Once the tool is updated successfully: " + repo_question(
            root, commit, tag, state
        )
    current = tool_version(install)
    return Offer(
        tool_question(state, current, tag) + follow_up,
        notice(tag, changes_between(current, tag, notes)),
    )


def instructions(
    cwd: str,
    state: reminders.State,
    release: Callable[[], tuple[str, str] | None] = latest_release,
    changelog: Callable[[str], str] | None = None,
) -> str:
    """What Claude is told to ask; empty when there is nothing to offer."""
    found = offer(cwd, state, release, changelog)
    return found.context if found else ""


def tool_status() -> str:
    """`up to date`, or the command that updates the installed tool (skill `/repo:update`)."""
    if is_beta():
        install = installed_kiln()
        return tool_update_command(install, "") if is_beta_tool_outdated(install) else "up to date"
    latest = latest_release()
    if latest is None:
        return "up to date"
    install = installed_kiln()
    if is_tool_outdated(install, *latest):
        return tool_update_command(install, latest[0])
    return "up to date"


def main() -> None:
    if sys.argv[1:] in ([TOOL_KEY], ["outil"]):
        print(tool_status())
        return
    try:
        payload = json.load(sys.stdin)
    except ValueError:
        payload = {}
    red, found = startup_context(payload)
    context = "\n\n".join(
        part
        for part in (
            ERROR_ORIGIN,
            SKILL_FRAME,
            red,
            found.context if found else "",
            launch_place(payload),
        )
        if part
    )
    session_id = payload.get("session_id", "")
    waiting = paused_sessions(payload)
    shown = "\n\n".join(part for part in (found.notice if found else "", waiting) if part)
    if shown:
        save_notice(session_id, shown)
    hook_output = {"hookEventName": "SessionStart", "additionalContext": context}
    print(json.dumps({"hookSpecificOutput": hook_output}, ensure_ascii=False))


def paused_sessions(payload: dict[str, Any]) -> str:
    """The sessions `/repo:pause` kept, shown above the first prompt of a new session; a resumed
    one leaves the list."""
    try:
        session_id = payload.get("session_id", "")
        source = payload.get("source", STARTUP_SOURCE)
        if source == "resume":
            paused.forget(session_id)
        return paused.listing(session_id) if source == STARTUP_SOURCE else ""
    except Exception:
        return ""


def launch_place(payload: dict[str, Any]) -> str:
    """Outside any repo: the repos below, and when to say a task belongs in one (`place.py`).
    Said again after a compaction or a /clear, which drop it."""
    try:
        return place.context(Path(payload.get("cwd") or ".").resolve())
    except Exception:
        return ""


def startup_context(payload: dict[str, Any]) -> tuple[str, Offer | None]:
    """At startup in a git repo: the red CI and the update question; nothing otherwise."""
    try:
        if payload.get("source", STARTUP_SOURCE) != STARTUP_SOURCE:
            return "", None
        cwd = payload.get("cwd") or "."
        root = git_root(cwd)
        if root is None:
            return "", None
        remove_legacy_link(root)
        state = reminders.load()
        found = offer(cwd, state)
        if kiln_repo(cwd) is not None:
            reminders.save(state)
        return (red_ci(root) if follows_kiln(root) else ""), found
    except Exception:
        # No network, GitHub rate limiting, unreadable repo: only the standing rule is said.
        return "", None


if __name__ == "__main__":
    main()
