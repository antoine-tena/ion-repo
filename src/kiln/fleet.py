"""`kiln status --all` and `kiln update --all`: every kiln repo of the code folder.

`update --all` never changes the branch of a repo's main tree: it works in a worktree
(`.claude/worktrees/`) started from the integration branch, commits in batches of ten files at
most, then merges straight into the integration branch and removes the worktree. Failed
checks: the branch is pushed without merging, to be taken up by hand.
"""

import datetime
import functools
import subprocess
import time
from collections import Counter
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path

from kiln import adopted, rehearsal, ui
from kiln.charter.config import CHARTER_FILE, LEGACY_CHARTER_FILE
from kiln.charter.waivers import Waivers, load
from kiln.check import run_checks
from kiln.config import load_config
from kiln.install import install_project
from kiln.shell import KilnError, capture, output_to, require_tools, run, step
from kiln.stack import ANSWERS_FILE, answers_if_any, load_stack, read_answers
from kiln.update import conflicted_files, update_project
from kiln.versions import is_beta, latest_release, release_version

KILN_SOURCE_MARKERS = ("antoine-tena/kiln", "antoine-tena/init-repo")
SEARCH_DEPTH = 3
# An adopted repo (not generated by kiln) is known by its charter: `status` shows it,
# `update --all` skips it, since applying the template would overwrite its handwritten files.
ADOPTED_MARKERS = (CHARTER_FILE, LEGACY_CHARTER_FILE)
SKIPPED_DIRS = frozenset({"node_modules", ".venv", ".git", ".claude", "_archives"})
WORKTREES_DIR = Path(".claude") / "worktrees"
UPDATE_BRANCH_PREFIX = "chore/kiln-update"
DEFAULT_INTEGRATION_BRANCH = "main"
# Preferred when origin has it: a clone does not always have `origin/HEAD`, and `main` is then
# often locked by a GitHub rule.
PREFERRED_INTEGRATION_BRANCH = "develop"
MAX_FILES_PER_COMMIT = 10
# pre-commit refuses to run while its changed configuration is not committed.
FIRST_COMMITTED = ".pre-commit-config.yaml"
COMMIT_ATTEMPTS = 2
# What each repo's update wrote, one log per repo and per run: the terminal gets one line each.
LOGS_DIR = Path.home() / ".cache" / "kiln" / "update-all"
# Outcomes with nothing left to do by hand.
DONE_OUTCOMES = ("merged into ", "already up to date", "rehearsal: ", "frozen")
FROZEN_OUTCOME = "frozen (kiln set frozen_repos): left as it is"


@dataclass(frozen=True)
class ManagedRepo:
    root: Path
    template_commit: str


def find_repos(code_dir: Path) -> list[ManagedRepo]:
    """Repos of the code folder generated by kiln (or by init-repo, its former name)."""
    repos = []
    for answers_path in _marker_files(code_dir, ANSWERS_FILE, SEARCH_DEPTH):
        root = answers_path.parent
        answers = read_answers(root)
        if (root / ".git").is_dir() and any(
            marker in str(answers.get("_src_path", "")) for marker in KILN_SOURCE_MARKERS
        ):
            repos.append(ManagedRepo(root, str(answers.get("_commit", ""))))
    return repos


def find_adopted(code_dir: Path) -> list[Path]:
    """Repos of the code folder that follow a kiln charter without being generated by kiln."""
    roots = {
        marker.parent
        for name in ADOPTED_MARKERS
        for marker in _marker_files(code_dir, name, SEARCH_DEPTH)
        if (marker.parent / ".git").is_dir() and not (marker.parent / ANSWERS_FILE).exists()
    }
    return sorted(roots)


def _marker_files(directory: Path, name: str, depth: int) -> list[Path]:
    found = [directory / name] if (directory / name).is_file() else []
    if depth == 0:
        return found
    for child in sorted(directory.iterdir()):
        if child.is_dir() and child.name not in SKIPPED_DIRS:
            found += _marker_files(child, name, depth - 1)
    return found


def template_state(commit: str, latest: str | None) -> str:
    """`v3 up to date`, `v2 → v3`, or the commit alone when the latest version is unknown."""
    latest_version = release_version(latest or "")
    if latest is None or latest_version is None:
        return commit or "?"
    current = release_version(commit)
    if current is not None and current >= latest_version:
        return f"{commit} up to date"
    return f"{commit or '?'} → {latest}"


def require_code_dir(code_dir: Path) -> None:
    """The code folder exists: otherwise, say where to set it rather than crash."""
    if not code_dir.is_dir():
        raise KilnError(
            f"code folder not found: {code_dir}. Set it in ~/.config/kiln/config.toml "
            '(code_dir = "<folder that holds your repos>")'
        )


STATUS_COLUMNS = (
    ("repo", 30),
    ("branch", 22),
    ("tree", 8),
    ("template", 24),
    ("size", 6),
    ("waived", 6),
)


def show_status(code_dir: Path) -> None:
    header = " ".join(f"{title:<{width}}" for title, width in STATUS_COLUMNS) + " stack"
    print(" ", ui.paint(header.upper(), ui.STONE, bold=True))
    latest = latest_release()
    waived: Counter[str] = Counter()
    for repo in find_repos(code_dir):
        state = template_state(repo.template_commit, latest)
        waived.update(_print_status(code_dir, repo.root, state))
    # On the beta channel, an adopted repo follows kiln's develop (`kiln update`).
    public = adopted.BETA_REF if is_beta() else latest_release(candidates=False)
    for root in find_adopted(code_dir):
        waived.update(_print_status(code_dir, root, adopted_state(root, public)))
    if waived:
        # A rule waived in several repos probably needs another look in kiln.
        counts = ", ".join(f"{target} ({n})" for target, n in waived.most_common())
        print(f"\n  Waivers (kiln-waivers.toml), by number of repos: {counts}")


def adopted_state(root: Path, public: str | None) -> str:
    """`adopted v0.4.0`, `adopted v0.3.4 → v0.4.0` when its workflows quote an older release."""
    refs = adopted.quoted_refs(root)
    if not refs:
        return "adopted"
    quoted = ", ".join(sorted(refs))
    if public is not None and refs != {public}:
        return f"adopted {quoted} → {public}"
    return f"adopted {quoted}"


def _state_color(state: str) -> ui.Color:
    """Green what is fine, fire what needs action, stone the rest."""
    if state.endswith("up to date"):
        return ui.MOSS
    return ui.FIRE if "→" in state else ui.STONE


def _print_status(code_dir: Path, root: Path, state: str) -> set[str]:
    """Line of the repo; returns the rules and files it waives."""
    waivers = load(root)
    branch = capture(["git", "branch", "--show-current"], root)
    is_dirty = bool(capture(["git", "status", "--porcelain"], root))
    stack = load_stack(root)
    size = answers_if_any(root).get("size", "?")
    tree_state = "dirty" if is_dirty else "clean"
    print(
        " ",
        ui.paint(f"{root.relative_to(code_dir)!s:<30}", bold=True),
        ui.paint(f"{branch:<22}", ui.STONE_LIGHT),
        ui.paint(f"{tree_state:<8}", ui.FIRE if is_dirty else ui.MOSS),
        ui.paint(f"{state:<18}", _state_color(state)),
        ui.paint(f"{size!s:<6}", ui.STONE),
        ui.paint(f"{_waiver_count(waivers):<6}", ui.FIRE if waivers.errors else ui.STONE),
        f"{stack.backend} + {stack.frontend}{' + podman' if stack.has_podman else ''}",
    )
    return {w.rule or f"file {w.file}" for w in waivers.actives}


def _waiver_count(waivers: Waivers) -> str:
    """Active waivers; `!` when one is expired or malformed."""
    if not (waivers.actives or waivers.errors):
        return "—"
    return f"{len(waivers.actives)}{' !' if waivers.errors else ''}"


def update_all(
    code_dir: Path, *, allow_major: bool, rehearse: bool = False, verbose: bool = False
) -> None:
    """Every repo updated and merged; with `rehearse`, each update played on a clone, nothing
    touched (before a promotion or an `update --all`). One line per repo, its output in a log;
    `verbose`: everything shown as it runs."""
    require_tools("git", "uv")
    # Generated repos replay the template; adopted ones only move kiln's workflows' tag.
    roots = [repo.root for repo in find_repos(code_dir)] + find_adopted(code_dir)
    frozen = {code_dir / repo for repo in load_config().frozen_repos}

    def work(root: Path) -> str:
        if root in frozen:
            return FROZEN_OUTCOME
        if rehearse:
            return rehearse_one(root, allow_major=allow_major)
        return update_one(root, allow_major=allow_major)

    if verbose:
        results = [(root, work(root)) for root in roots]
        step("Summary")
        for root, outcome in results:
            print(f"{root.relative_to(code_dir)!s:<30} {outcome}")
        return
    started = time.monotonic()
    logs = LOGS_DIR / datetime.datetime.now().astimezone().strftime("%Y-%m-%d-%H%M%S")
    logs.mkdir(parents=True, exist_ok=True)
    ui.note(f"\none line per repo, its full output in {logs} (--verbose: shown here)\n")
    width = max((len(str(root.relative_to(code_dir))) for root in roots), default=0)
    left = 0
    for root in roots:
        name = str(root.relative_to(code_dir))
        log = logs / f"{name.replace('/', '-')}.log"
        outcome = run_logged(f"{name:<{width}}", log, functools.partial(work, root))
        if not outcome.startswith(DONE_OUTCOMES):
            left += 1
            print(ui.paint(f"    log: {log}", ui.STONE_DARK), flush=True)
    total = ui.format_duration(time.monotonic() - started)
    if left:
        ui.note(f"\n{left} of {len(roots)} repos to finish by hand ({total}): each log says why")
    else:
        ui.success(f"{len(roots)} repos updated in {total}")


def run_logged(label: str, log: Path, work: Callable[[], str]) -> str:
    """Runs `work` with its output in `log`, a spinner on the terminal naming the current step,
    then one line: ✓ or ✗, the label, the outcome and the duration."""
    started = time.monotonic()
    with output_to(log) as terminal:
        spinner = ui.Spinner(label, stream=terminal) if ui.is_styled(terminal) else None
        if spinner is not None:
            spinner.start()
        try:
            with ui.steps_elsewhere(spinner):
                outcome = work()
        finally:
            if spinner is not None:
                spinner.stop()
    is_done = outcome.startswith(DONE_OUTCOMES)
    mark = ui.paint("✓", ui.MOSS) if is_done else ui.paint("✗", ui.EMBER, bold=True)
    first, *rest = outcome.splitlines() or [""]
    elapsed = ui.paint(ui.format_duration(time.monotonic() - started), ui.STONE_DARK)
    shown = first if is_done else ui.paint(first, ui.FIRE)
    print(f"  {mark} {ui.paint(label, bold=True)}  {shown}  {elapsed}", flush=True)
    for line in rest:
        print(f"    {line.strip()}", flush=True)
    return outcome


def rehearse_one(root: Path, *, allow_major: bool) -> str:
    step(f"Rehearsal of {root.name}, on a clone")
    try:
        outcome = rehearsal.rehearse(root, should_update_deps=True, allow_major=allow_major)
    except KilnError as error:
        return f"rehearsal failed: {error}"
    return f"rehearsal: {outcome.summary}"


def update_one(root: Path, *, allow_major: bool) -> str:
    """Updates a repo in a worktree then merges it straight into the integration branch
    ([NO-COMMIT-ON-MAIN]); on failed checks, the branch is pushed without merging. Returns the
    outcome in one line."""
    step(f"Repo {root.name}")
    integration = integration_branch(root)
    branch = f"{UPDATE_BRANCH_PREFIX}-{datetime.date.today().isoformat()}"
    worktree = root / WORKTREES_DIR / branch.replace("/", "-")
    try:
        _create_worktree(root, worktree, branch, integration)
        _update_worktree(worktree, allow_major=allow_major)
        # Checked only once the update is whole and changed something: the checks read the
        # conflicted files (pnpm-workspace.yaml), and a repo with nothing to take has no branch.
        conflicted = conflicted_files(worktree)
        if conflicted:
            return f"conflicts to resolve ({', '.join(conflicted)}) in {worktree}"
        if not capture(["git", "status", "--porcelain"], worktree):
            _remove_worktree(root, worktree, branch=branch)
            return "already up to date"
        failed_checks = run_checks(worktree)
        commit_in_batches(worktree)
        if failed_checks:
            run(["git", "push", "-q", "-u", "origin", branch], worktree)
            return (
                f"failed checks ({', '.join(failed_checks)}): branch {branch} pushed, "
                f"not merged, worktree {worktree}"
            )
        _merge_into_integration(worktree, branch, integration)
    except KilnError as error:
        try:
            cleared = _clear_stale_worktree(root, worktree, branch, integration)
        except KilnError:
            cleared = False
        if cleared:
            return f"failed: {error}"
        return f"failed: {error} (worktree left in {worktree})"
    _remove_worktree(root, worktree, branch=branch)
    return f"merged into {integration}"


def _update_worktree(worktree: Path, *, allow_major: bool) -> None:
    """Installs, then updates the template and dependencies."""
    install_project(worktree)
    update_project(
        worktree,
        should_update_template=True,
        should_update_deps=True,
        allow_major=allow_major,
        should_check=False,
    )


def integration_branch(root: Path) -> str:
    """`develop` when origin has it, otherwise origin's default branch; a repo not yet on
    GitHub (no origin) takes its local `develop` when there is one."""
    if _has_ref(root, f"refs/remotes/origin/{PREFERRED_INTEGRATION_BRANCH}"):
        return PREFERRED_INTEGRATION_BRANCH
    completed = subprocess.run(
        ["git", "symbolic-ref", "--short", "refs/remotes/origin/HEAD"],
        cwd=root,
        capture_output=True,
        text=True,
        check=False,
    )
    if completed.returncode == 0:
        return completed.stdout.strip().removeprefix("origin/")
    if _has_ref(root, f"refs/heads/{PREFERRED_INTEGRATION_BRANCH}"):
        return PREFERRED_INTEGRATION_BRANCH
    return DEFAULT_INTEGRATION_BRANCH


def _has_ref(root: Path, reference: str) -> bool:
    found = subprocess.run(
        ["git", "rev-parse", "--verify", "-q", reference],
        cwd=root,
        capture_output=True,
        check=False,
    )
    return found.returncode == 0


def _clear_stale_worktree(root: Path, worktree: Path, branch: str, integration: str) -> bool:
    """Removes the worktree and branch of an update that left nothing (no change, no commit of
    its own), so that the next one starts afresh; never a changed worktree. Returns true if
    nothing is left."""
    if worktree.exists():
        if capture(["git", "status", "--porcelain"], worktree):
            return False
        run(["git", "worktree", "remove", str(worktree)], root)
    run(["git", "worktree", "prune"], root)
    exists = subprocess.run(
        ["git", "rev-parse", "-q", "--verify", f"refs/heads/{branch}"],
        cwd=root,
        check=False,
        capture_output=True,
    )
    if exists.returncode != 0:
        return True
    own_commits = capture(["git", "rev-list", f"origin/{integration}..{branch}"], root)
    if own_commits:
        return False
    run(["git", "branch", "-q", "-D", branch], root)
    return True


def _create_worktree(root: Path, worktree: Path, branch: str, integration: str) -> None:
    run(["git", "fetch", "-q", "origin", integration], root)
    if not _clear_stale_worktree(root, worktree, branch, integration):
        raise KilnError(
            f"a previous update left work in {worktree} (branch {branch}):"
            " merge or remove it, then run again"
        )
    ignored = subprocess.run(
        ["git", "check-ignore", "-q", str(WORKTREES_DIR / "x")], cwd=root, check=False
    )
    if ignored.returncode != 0:
        with (root / ".git" / "info" / "exclude").open("a") as exclude:
            exclude.write(f"\n{WORKTREES_DIR.as_posix()}/\n")
    run(
        [
            "git",
            "worktree",
            "add",
            "-q",
            "--no-track",
            str(worktree),
            "-b",
            branch,
            f"origin/{integration}",
        ],
        root,
    )


def _remove_worktree(root: Path, worktree: Path, *, branch: str | None = None) -> None:
    run(["git", "worktree", "remove", "--force", str(worktree)], root)
    if branch is not None:
        run(["git", "branch", "-q", "-D", branch], root)


def commit_in_batches(worktree: Path) -> None:
    """Commits of ten files at most ([COMMITS]), grouped by top-level folder."""
    run(["git", "add", "-A"], worktree)
    changed = capture(["git", "diff", "--cached", "--name-only"], worktree).splitlines()
    run(["git", "reset", "-q"], worktree)
    groups: dict[str, list[str]] = {}
    if FIRST_COMMITTED in changed:
        groups["pre-commit"] = [FIRST_COMMITTED]
        changed.remove(FIRST_COMMITTED)
    for path in changed:
        groups.setdefault(path.split("/")[0] if "/" in path else "root", []).append(path)
    for group, paths in groups.items():
        for start in range(0, len(paths), MAX_FILES_PER_COMMIT):
            batch = paths[start : start + MAX_FILES_PER_COMMIT]
            _commit(worktree, batch, f"chore: kiln update, {group}"[:50])


def _commit(worktree: Path, paths: list[str], message: str) -> None:
    """Commit with the pre-commit hooks; a hook that fixes (ruff) gets a second try."""
    for _ in range(COMMIT_ATTEMPTS):
        run(["git", "add", "-A", "--", *paths], worktree)
        committed = subprocess.run(
            ["git", "commit", "-q", "-m", message], cwd=worktree, check=False
        )
        if committed.returncode == 0:
            return
    raise KilnError(f"commit refused by the hooks: {message}")


def _merge_into_integration(worktree: Path, branch: str, integration: str) -> None:
    """Merge commit on top of the published integration branch, pushed as is ([MERGE])."""
    run(["git", "fetch", "-q", "origin", integration], worktree)
    run(["git", "switch", "-q", "--detach", f"origin/{integration}"], worktree)
    run(
        [
            "git",
            "merge",
            "-q",
            "--no-ff",
            branch,
            "-m",
            f"Merge branch '{branch}' into {integration}",
        ],
        worktree,
    )
    run(["git", "push", "-q", "origin", f"HEAD:{integration}"], worktree)
